create or replace function public.record_sale(p_item_id bigint,p_qty numeric,p_date date,p_payment text)
returns void language plpgsql security definer set search_path=public as $$
declare x items%rowtype;
begin
select * into x from items where id=p_item_id for update;
if not found then raise exception 'Item not found'; end if;
if p_qty<=0 or x.stock<p_qty then raise exception 'Insufficient stock'; end if;
if p_payment not in('Cash','UPI','Card') then raise exception 'Invalid payment'; end if;
update items set stock=stock-p_qty where id=p_item_id;
insert into sales(item_id,name,qty,sell,buy,revenue,profit,payment,date)
values(x.id,x.name,p_qty,x.sell_price,x.buy_price,p_qty*x.sell_price,p_qty*(x.sell_price-x.buy_price),p_payment,p_date);
end $$;

create or replace function public.record_purchase(p_item_id bigint,p_qty numeric,p_price numeric,p_supplier text)
returns void language plpgsql security definer set search_path=public as $$
declare x items%rowtype;
begin
select * into x from items where id=p_item_id for update;
if not found then raise exception 'Item not found'; end if;
if p_qty<=0 or p_price<0 then raise exception 'Invalid purchase'; end if;
update items set stock=stock+p_qty,buy_price=p_price where id=p_item_id;
insert into purchases(item_id,name,qty,price,total,supplier,date)
values(x.id,x.name,p_qty,p_price,p_qty*p_price,p_supplier,current_date);
end $$;

grant execute on function public.record_sale(bigint,numeric,date,text) to authenticated;
grant execute on function public.record_purchase(bigint,numeric,numeric,text) to authenticated;


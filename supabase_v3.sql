create table if not exists public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 name text,email text,role text not null default 'staff' check(role in('owner','staff')),
 created_at timestamptz not null default now());

create table if not exists public.items(
 id bigint generated by default as identity primary key,name text not null,
 category text not null default 'Other',buy_price numeric(12,2) not null default 0,
 sell_price numeric(12,2) not null default 0,stock numeric(12,2) not null default 0,
 min_stock numeric(12,2) not null default 0,unit text not null default 'pcs',
 created_at timestamptz not null default now());

create table if not exists public.sales(
 id bigint generated by default as identity primary key,item_id bigint references public.items(id) on delete restrict,
 name text not null,qty numeric(12,2) not null,sell numeric(12,2) not null,buy numeric(12,2) not null,
 revenue numeric(12,2) not null,profit numeric(12,2) not null,
 payment text not null default 'Cash' check(payment in('Cash','UPI','Card')),
 date date not null default current_date,created_at timestamptz not null default now());

create table if not exists public.purchases(
 id bigint generated by default as identity primary key,item_id bigint references public.items(id) on delete restrict,
 name text not null,qty numeric(12,2) not null,price numeric(12,2) not null,total numeric(12,2) not null,
 supplier text,date date not null default current_date,created_at timestamptz not null default now());

create table if not exists public.expenses(
 id bigint generated by default as identity primary key,category text not null,
 amount numeric(12,2) not null,note text,date date not null default current_date,
 created_at timestamptz not null default now());

create table if not exists public.daily_closings(
 id bigint generated by default as identity primary key,
 date date unique not null,opening_cash numeric(12,2) not null default 0,
 cash_sales numeric(12,2) not null default 0,cash_expenses numeric(12,2) not null default 0,
 expected_cash numeric(12,2) not null default 0,actual_cash numeric(12,2) not null default 0,
 difference numeric(12,2) not null default 0,created_at timestamptz not null default now(),
 closed_by uuid references auth.users(id));

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.profiles(id,name,email,role) values(new.id,coalesce(new.raw_user_meta_data->>'name',''),new.email,'staff') on conflict(id) do nothing; return new; end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_owner() returns boolean language sql stable security definer set search_path=public as $$
select exists(select 1 from public.profiles where id=auth.uid() and role='owner'); $$;

